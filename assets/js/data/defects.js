  /* 矢印（k：'' 墨、b 不良色、k 良、m 淡、a アクセント、w 白抜き） */
  function A(x1, y1, x2, y2, k) { k = k || ''; return L(x1, y1, x2, y2, LN[k], ' marker-end="url(#dxAr' + k + ')"'); }
  function AP(d, k) { k = k || ''; return P(d, LN[k] + ' dx-nf', ' marker-end="url(#dxAr' + k + ')"'); }
  /* 文字。\n で改行 */
  function T(x, y, s, c, anchor) {
    var lines = String(s).split('\n');
    var inner = lines.length === 1 ? lines[0] : lines.map(function (ln, i) { return '<tspan x="' + x + '" dy="' + (i ? '1.2em' : '0') + '">' + ln + '</tspan>'; }).join('');
    return '<text' + at({ x: x, y: y, 'text-anchor': anchor }) + ' class="' + (c || 'dx-t') + '">' + inner + '</text>';
  }
  /* 引き出し線（(x2,y2) が指す点。先に小さな点） */
