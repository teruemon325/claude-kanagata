  function at(o) { var s = ''; for (var k in o) if (o[k] != null) s += ' ' + k + '="' + o[k] + '"'; return s; }
  function P(d, c, x) { return '<path d="' + d + '" class="' + c + '"' + (x || '') + '/>'; }
  function R(x, y, w, h, c, x2) { return '<rect' + at({ x: x, y: y, width: w, height: h }) + ' class="' + c + '"' + (x2 || '') + '/>'; }
  function C(cx, cy, r, c, x) { return '<circle' + at({ cx: cx, cy: cy, r: r }) + ' class="' + c + '"' + (x || '') + '/>'; }
  function E(cx, cy, rx, ry, c, x) { return '<ellipse' + at({ cx: cx, cy: cy, rx: rx, ry: ry }) + ' class="' + c + '"' + (x || '') + '/>'; }
  function L(x1, y1, x2, y2, c, x) { return '<line' + at({ x1: x1, y1: y1, x2: x2, y2: y2 }) + ' class="' + c + '"' + (x || '') + '/>'; }
